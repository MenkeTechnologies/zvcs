const V2_LS_REFS_UNBORN: &[u8] =
    b"0014command=ls-refs\n0017object-format=sha1\n0001000csymrefs\n000bunborn\n0000";

/// v2 `ls-refs` carrying a `server-option`. The v2 advertisement claims
/// `server-option`; this is the request that makes the server prove it accepts
