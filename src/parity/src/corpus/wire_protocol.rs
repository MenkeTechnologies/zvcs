/// cases, because the refusal is as much a wire fact as the answer.
const V2_OBJECT_INFO: &[u8] =
    b"0018command=object-info\n0017object-format=sha1\n00010009size\n0031oid 91bfcd8dad4adbba6d1110e504c5bd1929984f2c\n0000";

/// v2 `fetch` wanting an object it already has. The `have` is what makes the
