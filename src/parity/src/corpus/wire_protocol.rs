const V2_FETCH_WANT_HAVE: &[u8] =
    b"0012command=fetch\n0017object-format=sha1\n0001000ethin-pack\n000eofs-delta\n0032want 91bfcd8dad4adbba6d1110e504c5bd1929984f2c\n0032have 91bfcd8dad4adbba6d1110e504c5bd1929984f2c\n0009done\n0000";

/// The v0 spelling of the same negotiation: `want` with a capability list, a
