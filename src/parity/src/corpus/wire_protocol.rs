//! The pack protocol itself: the four wire verbs as *servers*, the bytes they
//! read and write, and the version negotiation that decides which dialect they
//! speak.
//!
//! Every other transport module in the corpus measures a **client**. This one
//! measures the wire: `upload-pack` and `receive-pack` driven by a pkt-line
//! request written into the case as a byte literal, `git daemon` serving one
//! request over stdin, and the `GIT_PROTOCOL` handshake that selects v0, v1 or
//! v2 before either end has said anything else.
//!
//! # How this divides territory with the five adjacent modules
//!
//! * **`fetch_clone.rs`** owns `fetch`, `clone`, `bundle`, `ls-remote` and the
//!   *option surface* of the four pack verbs against `Shape::BehindRemote`'s
//!   peer. Its `upload_pack`, `send_pack`, `receive_pack` and `fetch_pack`
//!   groups run every one of them with **stdin closed**, so what they measure is
//!   the advertisement a server prints before it reads anything and the report a
//!   client prints after. It never writes a request. Its `protocol.version`
//!   cases are three `fetch origin main:refs/heads/x` invocations and one
//!   `-c protocol.version=2` apiece on `upload-pack`, `send-pack` and
//!   `fetch-pack`; that is the whole of the version axis in the corpus, and it
//!   is entirely *client-side config*. This module owns the other half — the
//!   `GIT_PROTOCOL` variable, which is how the version is actually negotiated,
//!   and which no case in the corpus set before.
//! * **`transport_local.rs`** owns the self-referential spelling of the same
//!   verbs (`fetch .`, `push .`, `upload-archive`) on the shapes with no peer.
//!   Its header records that both ends of every one of its cases is the *same*
//!   binary running as a client; nothing there drives a server directly.
//! * **`branch_remote.rs`** owns `push` and the remote-tracking bookkeeping
//!   underneath it, including `--receive-pack=git-receive-pack`.
//! * **`refspec_algebra.rs`** owns the refspec **grammar** — which name matches
//!   which, and where it lands. The two cases here that carry a refspec
//!   (`send-pack --all`, `send-pack --mirror`) are not about matching: `--all`
//!   and `--mirror` name a *ref set* rather than a pattern, and what they
//!   measure is which set the verb chose and whether it forced.
//! * **`interchange.rs`** owns bundles — the offline spelling of the same object
//!   transfer, with no protocol at all.
//!
//! # Why a request has to be a literal, and how the lengths were checked
//!
//! A server is only measurable if something speaks to it, and the harness's one
//! channel into a case is `Case::stdin`, which is `&'static [u8]`. So every
//! request below is a pkt-line stream written out by hand: a four-hex length
//! that *includes its own four bytes*, then the payload; `0000` is a flush and
//! `0001` a delimiter. Each was generated by a length-computing script, written
//! to a file, and replayed against stock 2.55.0 before being transcribed here —
//! a length that is one byte wrong does not fail loudly, it makes the server
//! read a truncated command and answer a question nobody asked, on both sides,
//! identically.
//!
//! The object ids inside them are the peer's, and they are fixed facts of
//! [`Shape::BehindRemote`]: `refs/heads/main` is
//! `91bfcd8dad4adbba6d1110e504c5bd1929984f2c` and `refs/heads/div` is
//! `79f764eb810204174b975d237db6fd14984a72bd` — the same two ids
//! `refspec_algebra.rs`'s header quotes, verified again here by rebuilding the
//! shape from `fixture.rs`'s recipe with stock 2.55.0.
//!
//! # What is NOT measurable here, established by measurement rather than by
//! taste
//!
//! * **A crossed client/server pair.** The highest-value question in this
//!   territory — stock's client talking to the port's server — is not
//!   expressible in this harness, and no case below pretends otherwise. A `Case`
//!   is one argv run twice, once per binary, and the *server* a transport spawns
//!   is chosen by the client: measured with a `git-upload-pack` shim on `PATH`,
//!   stock's `fetch-pack` resolves the helper through its own `GIT_EXEC_PATH`
//!   and never sees the shim, while the port's resolves it through `PATH` and
//!   hits it twice. So on **both** sides of every `fetch-pack ./.remote.git`
//!   case in the corpus the far end is stock's `git-upload-pack`, and the only
//!   way to change that is `--upload-pack=<path>`, which would have to name an
//!   absolute path — the same path on both sides, which crosses nothing. The
//!   substitute this module ships instead is to drive the port's server half
//!   *directly* with the bytes a stock client would have sent, and compare the
//!   bytes it answers with. That is the same wire, minus the second process.
//! * **`git daemon` as a listener.** A port, a pid and an accept loop; none of
//!   the three is comparable. `--inetd` is the same server reading one request
//!   from stdin and is fully deterministic — verified, twice per side, with no
//!   timestamp, pid or socket path anywhere in its output — so that is the
//!   spelling [`daemon_inetd`] uses and the listening mode appears nowhere.
//! * **`receive.certNonceSeed`.** It puts `push-cert=<unix timestamp>-<hmac>` in
//!   the advertisement. `fetch_clone.rs` excluded it for that reason and it is
//!   excluded here for the same one.
//! * **A v0 `want`/`done` that transfers a real pack.** Measured and rejected:
//!   `upload-pack --stateless-rpc ./.remote.git` fed a bare `want`+`done` gives
//!   stock three different SHA-1s over three runs, because the pack it builds is
//!   not byte-stable. The two pack-bearing requests that *are* here
//!   ([`V0_WANT_HAVE_DONE`] and [`V2_FETCH_WANT_HAVE`]) both carry a `have` for
//!   the object they `want`, so the pack is empty and its bytes are a constant —
//!   verified eight times and five times respectively against stock, identical
//!   every run, and twice more against the port.
//! * **`send-pack --force-with-lease=<ref>` against the peer.** Stock 2.55.0
//!   **crashes** on it here: exit 139, `fatal: the remote end hung up
//!   unexpectedly`, reproducible. A case pinned on a stock segfault measures the
//!   oracle, not the port, so it is recorded here and not shipped.
//! * **`--timeout=<n>`.** Real seconds. `fetch_clone.rs` already carries the one
//!   spelling that returns without waiting (`--timeout=1 --advertise-refs`);
//!   nothing here adds another.
//!
//! # Determinism of what *is* here
//!
//! Every case below was run twice against stock in a hand-built copy of its
//! shape and twice against the port, and the four answers compared on stdout,
//! stderr, exit code and repository state. The one candidate that failed that
//! gate is the bare `want`/`done` named above, and it was dropped rather than
//! weakened. `--shallow-since` appears only with a literal ISO date on either
//! side of the fixtures' pinned commit clock (`env::harden` fixes every commit
//! at `1700000000`), never with an approxidate that reads the wall clock.

use crate::fixture::Shape;
use crate::runner::{Case, ConfigEntry, ConfigScope};

/// [`Case::strict`] with a stdin payload: the two constructors do not compose,
/// and half this module needs both.
fn strict_stdin(
    cmd: &'static str,
    args: &[&str],
    shape: Shape,
    stdin: &'static [u8],
) -> Case {
    let mut case = Case::with_stdin(cmd, args, shape, stdin);
    case.compare_stderr = true;
    case
}

/// Append this subsystem's cases to the corpus.
pub fn cases(out: &mut Vec<Case>) {
    protocol_version_selection(out);
    server_version_line(out);
    upload_pack_v2_capabilities(out);
    upload_pack_v2_commands(out);
    upload_pack_v0_requests(out);
    upload_pack_hidden_refs(out);
    receive_pack_reports(out);
    receive_pack_advertisement(out);
    fetch_pack_shallow_wire(out);
    fetch_pack_diag_url(out);
    send_pack_ref_selection(out);
    send_pack_wire_modes(out);
    ls_remote_protocol(out);
    daemon_inetd(out);
}

